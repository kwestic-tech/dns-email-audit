#!/usr/bin/env node
/**
 * Rebuild `tests/state-matrix.json`'s coverage columns from EVIDENCE.
 *
 *   node tests/build/coverage.mjs            report the gap
 *   node tests/build/coverage.mjs --write    rewrite the matrix from what ran
 *
 * `fixtures` is measured: every corpus case is run and its results are walked
 * along the `resultPaths` the registry declares, so a case covers a member
 * because the member was observed, not because someone read the fixture and
 * concluded it would be.
 *
 * `suites` is REVIEWED, and short. An earlier draft seeded it by scanning the
 * v0.5.0 suites for each member as a string literal, which handed coverage
 * credit to `ds`, `key`, `no` and `ok` for appearing incidentally in an
 * unrelated assertion. A coverage claim that nobody checked against what ran is
 * the same defect as a suite passing against the wrong public suffix list, so
 * the scan was withdrawn and only assignments backed by a named assertion
 * remain.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { runCase } from './equivalence.mjs';
import { cases } from '../fixtures/equivalence/corpus.mjs';
import { observedMembers, mergeCoverage } from '../lib/coverage.mjs';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

/**
 * Coverage `tests/contract/legacy-shapes.test.mjs` provides, by review.
 *
 * Each entry points at a section of that file that asserts the member. Nothing
 * is here because a string happened to appear.
 */
const REVIEWED_SUITES = {
  'tests/contract/legacy-shapes.test.mjs': {
    'dns.transport.kind': ['success', 'nodata', 'nxdomain', 'servfail', 'refused',
      'dns-error', 'http-error', 'cancelled', 'timeout', 'network-error'],
    'dns.retryTerminal': ['success', 'nodata', 'nxdomain', 'cancelled'],
    'dns.cacheable': ['success', 'nodata', 'nxdomain'],
    'dns.usable': ['success', 'nodata', 'nxdomain'],
    'dns.thrown': ['DnsTypeError', 'AbortError', 'DnsQueryError'],
    'dns.optionalCheck.rethrow': ['AbortError', 'DnsTypeError'],
    'dns.existence': ['yes', 'no', 'unknown'],
    'dkim.key.keyType': ['rsa'],
    'dkim.key.keyEncoding': ['null'],
    'dkim.key.version': ['null', 'DKIM1'],
    'dkim.key.cryptoValidated': ['null'],
    'dkim.key.errors': ['missing-p'],
    'dmarc.version.reason': ['null', 'absent', 'not-first', 'bad-value'],
    'dmarc.diagnosis': ['null', 'version-bad-case', 'version-not-first', 'version-absent'],
    'dmarc.status': ['permerror'],
    'dmarc.appliedBranch': ['np', 'weakest'],
    'dmarc.reportAuth.record.reason': ['null', 'version', 'syntax'],
    'dnssec.chain.claim': ['ds-no-matching-key'],
    'dnssec.ds.unverifiableReason': ['invalid-owner', 'unbuildable-key'],
    'dnssec.ds.match': ['no-matching-key'],
    'dnssec.error': ['undefined', 'cancelled'],
    'caa.knownTags': ['issue'],
    // Section 6 asserts the whole 106-token vocabulary as a set closure against
    // locales/en.json, which is a stronger statement than any per-token check.
    'audit.issue.key': '*',
  },
};

const registry = JSON.parse(readFileSync(join(REPO, 'tests/state-algebras.json'), 'utf8'));
const matrix = JSON.parse(readFileSync(join(REPO, 'tests/state-matrix.json'), 'utf8'));

const perCase = [];
for (const testCase of cases) {
  const surfaces = await runCase(REPO, testCase, 'classic');
  perCase.push([testCase.id, observedMembers(registry, surfaces.result)]);
}
const coverage = mergeCoverage(perCase);

const rows = [];
const uncovered = [];
for (const algebra of registry.algebras) {
  for (const member of algebra.members) {
    const suites = [];
    for (const [suite, covered] of Object.entries(REVIEWED_SUITES)) {
      const entry = covered[algebra.id];
      if (entry === '*' || (Array.isArray(entry) && entry.includes(member))) suites.push(suite);
    }
    const fixtures = coverage.get(`${algebra.id} ${member}`) || [];
    rows.push({ algebra: algebra.id, member, suites, fixtures });
    if (!suites.length && !fixtures.length) uncovered.push(`${algebra.id} :: ${member}`);
  }
}

matrix.rows = rows;
matrix.$comment = [
  'Coverage matrix for tests/state-algebras.json. Spec §12.1 and Testing item 3.',
  'One row per registry member. A row must name at least one suite or one corpus case.',
  'REGENERATED by tests/build/coverage.mjs --write, not hand-edited.',
  '`fixtures` is MEASURED: every case is run and its results are walked along the',
  'registry’s resultPaths, so a case covers a member because the member was observed.',
  '`suites` is REVIEWED and short — each entry points at a named assertion in',
  'tests/contract/legacy-shapes.test.mjs. An earlier draft seeded this column by',
  'scanning the suites for each member as a string literal, which gave `ds`, `key`,',
  '`no` and `ok` credit for appearing incidentally. That scan was withdrawn.',
  'A member the corpus cannot reach is framework §6 trigger 3 — stop and write a review.',
];

if (process.argv.includes('--write')) {
  writeFileSync(join(REPO, 'tests/state-matrix.json'), JSON.stringify(matrix, null, 2) + '\n');
}

console.log(`cases ${cases.length}  rows ${rows.length}  covered ${rows.length - uncovered.length}  uncovered ${uncovered.length}`);
if (uncovered.length) console.log('\n' + uncovered.join('\n'));

#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const repo = join(dirname(fileURLToPath(import.meta.url)), '..');
const input = process.argv[2];

if (!input) {
  console.error('Usage: node tools/update-dkim-selectors.mjs /path/to/recognized_dkim_selectors.md');
  process.exit(1);
}

const source = await readFile(resolve(input), 'utf8');
const rowPattern = /^\| `([^`]+)` \| ([^|]+?) \| ([^|]+?) \| ([^|]+?) \|\r?$/gm;
const rows = [];
let match;

while ((match = rowPattern.exec(source))) {
  rows.push({
    selector: match[1].trim().toLowerCase(),
    provider: match[2].trim(),
    category: match[3].trim(),
    notes: match[4].trim(),
  });
}

if (!rows.length) throw new Error('No selector rows found in the supplied Markdown catalog.');

const seen = new Set();
for (const row of rows) {
  if (!/^[a-z0-9][a-z0-9_-]{0,62}$/.test(row.selector)) {
    throw new Error(`Invalid selector: ${row.selector}`);
  }
  if (seen.has(row.selector)) throw new Error(`Duplicate selector: ${row.selector}`);
  seen.add(row.selector);
}

const catalog = { providers: {}, generic: [], temporal: [], prefixes: [] };
for (const row of rows) {
  if (/prefix/i.test(row.notes) && /[-_]$/.test(row.selector)) {
    catalog.prefixes.push(row.selector);
  } else if (row.category === 'Temporal & Date-Based Selectors') {
    catalog.temporal.push(row.selector);
  } else if (row.category === 'Generic & System Conventions') {
    catalog.generic.push(row.selector);
  } else {
    (catalog.providers[row.provider] ||= []).push(row.selector);
  }
}

catalog.providers = Object.fromEntries(
  Object.entries(catalog.providers).sort(([a], [b]) => a.localeCompare(b))
);

const generated = `/* AUTO-GENERATED by tools/update-dkim-selectors.mjs.
 * Source: user-supplied recognized DKIM selector catalog.
 * ${rows.length} unique catalog entries: exact selectors and recognized prefixes.
 * Do not edit this file directly.
 */
(function (global) { 'use strict'; global.__DKIM_SELECTOR_CATALOG__ = ${JSON.stringify(catalog)}; })(window);
`;

await writeFile(join(repo, 'js', 'dkim-selectors.js'), generated, 'utf8');
console.log(
  `Wrote ${rows.length} entries (${Object.keys(catalog.providers).length} providers, ` +
  `${catalog.generic.length} generic, ${catalog.temporal.length} temporal, ` +
  `${catalog.prefixes.length} non-queryable prefixes) to js/dkim-selectors.js`
);

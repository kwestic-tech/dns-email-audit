#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const repo = join(dirname(fileURLToPath(import.meta.url)), '..');
const input = process.argv[2];
const excludedFixedGuesses = new Map([
  ['Amazon SES (Simple Email Service)', new Set(['amazonses', 'amazonses2', 'aws', 'aws1', 'aws2', 'ses'])],
]);

let catalog;

if (input) {
  const source = await readFile(resolve(input), 'utf8');
  const rowPattern = /^\| `([^`]+)` \| ([^|]+?) \| ([^|]+?) \| ([^|]+?) \|\r?$/gm;
  const rows = [];
  let match;

  while ((match = rowPattern.exec(source))) {
    rows.push({
      selector: match[1].trim().toLowerCase(),
      provider: match[2].trim(),
      category: match[3].trim(),
      notes: match[4].trim(),
    });
  }
  if (!rows.length) throw new Error('No selector rows found in the supplied Markdown catalog.');

  const seen = new Set();
  catalog = { providers: {}, generic: [], temporal: [], prefixes: [], excluded: [] };
  for (const row of rows) {
    if (!/^[a-z0-9][a-z0-9_-]{0,62}$/.test(row.selector)) {
      throw new Error(`Invalid selector: ${row.selector}`);
    }
    if (seen.has(row.selector)) throw new Error(`Duplicate selector: ${row.selector}`);
    seen.add(row.selector);
    if (/prefix/i.test(row.notes) && /[-_]$/.test(row.selector)) {
      catalog.prefixes.push(row.selector);
    } else if (row.category === 'Temporal & Date-Based Selectors') {
      catalog.temporal.push(row.selector);
    } else if (row.category === 'Generic & System Conventions') {
      catalog.generic.push(row.selector);
    } else {
      (catalog.providers[row.provider] ||= []).push(row.selector);
    }
  }
} else {
  const generatedSource = await readFile(join(repo, 'src', 'data', 'dkim-selectors.js'), 'utf8');
  const serialized = generatedSource.match(/export const DKIM_SELECTOR_CATALOG = (.*);\s*$/s)?.[1];
  if (!serialized) throw new Error('Could not read the existing generated DKIM catalog.');
  catalog = JSON.parse(serialized);
  catalog.providers ||= {};
  catalog.generic ||= [];
  catalog.temporal ||= [];
  catalog.prefixes ||= [];
  catalog.excluded ||= [];
}

for (const [provider, selectors] of excludedFixedGuesses) {
  const providerSelectors = catalog.providers[provider] || [];
  catalog.providers[provider] = providerSelectors.filter(selector => !selectors.has(selector));
  for (const selector of selectors) {
    if (!providerSelectors.includes(selector) && !catalog.excluded.some(item => item.selector === selector)) continue;
    if (!catalog.excluded.some(item => item.selector === selector)) {
      catalog.excluded.push({
        selector,
        provider,
        reason: 'SES Easy DKIM uses generated tokens; this fixed name is not an authoritative convention.',
      });
    }
  }
  if (!catalog.providers[provider].length) delete catalog.providers[provider];
}

catalog.providers = Object.fromEntries(
  Object.entries(catalog.providers).sort(([a], [b]) => a.localeCompare(b))
);

const queryableCount = Object.values(catalog.providers).flat().length + catalog.generic.length + catalog.temporal.length;
const entryCount = queryableCount + catalog.prefixes.length + catalog.excluded.length;

const generated = `/* AUTO-GENERATED by tools/update-dkim-selectors.mjs.
 * Source: user-supplied recognized DKIM selector catalog.
 * ${entryCount} unique catalog entries: queryable selectors, prefixes, and excluded guesses.
 * Do not edit this file directly.
 */

export const DKIM_SELECTOR_CATALOG = ${JSON.stringify(catalog)};
`;

await writeFile(join(repo, 'src', 'data', 'dkim-selectors.js'), generated, 'utf8');
console.log(
  `Wrote ${entryCount} entries (${queryableCount} queryable, ${Object.keys(catalog.providers).length} providers, ` +
  `${catalog.generic.length} generic, ${catalog.temporal.length} temporal, ` +
  `${catalog.prefixes.length} non-queryable prefixes, ${catalog.excluded.length} excluded guesses) ` +
  `to src/data/dkim-selectors.js`
);
